// Package ts renders Remit's plugin contract as TypeScript. remit.d.ts is
// generated from the same tables the host validates against — the hook
// vocabulary, the capability names, the contribution schema — so the file a
// plugin author reads and the host that runs the plugin cannot drift apart
// without the drift test failing.
package ts

import (
	"fmt"
	"sort"
	"strings"

	"github.com/transmit-bug/remit/internal/ext"
	"github.com/transmit-bug/remit/internal/ext/contrib"
)

// FileName is the artifact's name at the repository root.
const FileName = "remit.d.ts"

// Render is remit.d.ts: the contract of this build's host API, versioned by
// ext.HostAPIVersion.
func Render() []byte {
	var b strings.Builder

	fmt.Fprintf(&b, "// Code generated by `go run ./cmd/remit ext types`; DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Remit's plugin contract, host API version %d.\n//\n", ext.HostAPIVersion)
	fmt.Fprintf(&b, `// A manifest's apiVersion names the version of this file its plugin was
// written for; the host loads anything from 1 up to its own. A breaking change
// bumps it. protocol is the exec wire protocol and is not this number.
//
// The shapes below are the ones internal/ext and internal/ext/contrib validate:
// a hook in implements outside Hook is refused, a capability outside Capability
// is refused, and a contribution the host cannot keep is dropped on its own,
// with the reason.

/** The host API version this file describes. */
export declare const apiVersion: %d;

// ─── manifest ──────────────────────────────────────────────────────────────

/** A hook id a manifest's implements may name. */
export type Hook = %s;

/**
 * Each hook's contract version, which a manifest declares beside the hook:
 * implements: { deriveBlock: 1 }. A version above this map's is refused.
 */
export interface HookContracts {
%s}

/** A capability a manifest may declare; the host offers nothing else. */
export type Capability = %s;

export interface Manifest {
  /** A js plugin's stable identity; a derived card's producer stamp carries it. */
  id?: string;
  /** The name the library's enabled list and the app's log line use. */
  name: string;
  version?: string;
  /** The host API the plugin was written for: 1 through %d. */
  apiVersion?: number;
  /** "js" for JavaScript in this process; absent or "exec" for a program on its pipes. */
  runtime?: "js" | "exec";
  /** A js plugin's file, relative to its own directory; ".." and absolute paths are refused. */
  entry?: string;
  /** An exec plugin's command and arguments. */
  entrypoint?: string[];
  /** The exec wire protocol: %d. A js manifest must not carry it. */
  protocol?: number;
  implements?: Partial<HookContracts>;
  /** When the plugin would like to be loaded. Recorded today, not acted on. */
  activation?: string[];
  /** The card types a derive plugin answers; the library must already hold them. */
  produces?: string[];
  capabilities?: Capability[];
  contributes?: Contributes;
}

`, ext.HostAPIVersion, union(hookNames()), hookContracts(), union(ext.Capabilities), ext.HostAPIVersion, ext.Protocol)

	fmt.Fprintf(&b, `// ─── what a plugin adds to the window ──────────────────────────────────────

/** A %%key%% naming an entry of the plugin's own catalog, or a literal. */
export type Message = string;

/** A when expression: !, &&, ||, ==, !=, parentheses, string and number literals. */
export type When = string;

/** A menu slot the host owns; a plugin cannot invent a place in the window. */
export type MenuSlot = %s;

/** Where a page appears: the host's plugin pages, or nowhere (a command opens it). */
export type Nav = %s;

export type SettingType = %s;

/** One of the app's own actions; a command names one, or a command: callback. */
export type HostAction = %s;

export interface Contributes {
  commands?: Command[];
  menus?: Partial<Record<MenuSlot, MenuItem[]>>;
  pages?: Page[];
  settings?: Setting[];
  /** The plugin's own strings, by locale: a %%key%% title resolves here. */
  locales?: Record<string, Record<string, string>>;
}

export interface Command {
  /** Globally unique; the remit. prefix is the host's. */
  id: string;
  title: Message;
  category?: Message;
  /** A name in the host's icon set; an unknown name drops the command. */
  icon?: string;
  /** The accelerator the host binds; two plugins claiming one is reported. */
  keybinding?: string;
  when?: When;
  action: HostAction | `+"`command:${string}`"+`;
}

export interface MenuItem {
  /** One of this plugin's command ids. */
  command: string;
  group?: "primary" | "secondary" | "plugin";
  order?: number;
  when?: When;
}

export interface Page {
  id: string;
  title: Message;
  icon?: string;
  /** "plugins" (the default) or "hidden". */
  nav?: Nav;
  when?: When;
  /** The command that answers the page's node tree: command:<name>. */
  data: string;
}

export interface Setting {
  key: string;
  type: SettingType;
  title: Message;
  /** A bool, a number or a string, as type says. */
  default?: boolean | number | string;
}

`, union(contrib.Slots), quotedAll(navNames()), quotedAll(settingTypeNames()), union(hostActionNames()))

	fmt.Fprintf(&b, `// ─── the window a when expression reads ────────────────────────────────────

/** A key a when expression may read. An unknown key reads false, with a warning. */
export type ContextKey = %s;

export type Mode = "notes" | "review" | "browse" | "stats" | "settings" | "";

/** A card's standing. A lost reference is a LinkState, not a status. */
export type CardStatus = "new" | "learning" | "review" | "suspended" | "reading";

export interface Context {
%s}

`, union(contrib.ContextKeys), contextFields())

	fmt.Fprintf(&b, `// ─── a page's tree ─────────────────────────────────────────────────────────

/** A layout node the host arranges, or a semantic leaf it draws. */
export type NodeKind = %s;

export type Gap = %s;
export type Tone = %s;
export type StackDirection = %s;

/**
 * One node of a page. The host draws it: there is no width, height, colour,
 * font, margin, padding or position. Depth <= %d, nodes <= %d, table rows <= %d,
 * one page <= %d bytes; over any of them the page shows its error state.
 */
export interface Node {
  kind: NodeKind;
  title?: string;
  description?: string;
  children?: Node[];
  /** A stack's order: "column" (the default) or "row", which the host wraps. */
  direction?: StackDirection;
  gap?: Gap;
  tone?: Tone;
  /** A grid's column hint (1-4), or a table's headings. */
  columns?: number | string[];
  /** A split's share: 1 for equal panes, 2 for one twice the other. */
  ratio?: 1 | 2;
  tabs?: Tab[];
  label?: string;
  value?: string;
  text?: string;
  /** A table's cells. */
  rows?: string[][];
  /** A list's, tree's or actions' rows. */
  items?: Item[];
  /** A form's rows. */
  fields?: Item[];
  /** A chart's bars. */
  points?: Point[];
}

export interface Tab {
  label: string;
  children: Node[];
}

export interface Item {
  label?: string;
  value?: string;
  /** An actions row's command: one of this plugin's command ids. */
  command?: string;
  items?: Item[];
}

export interface Point {
  label: string;
  value: number;
}

/** A page's data command answers one of these. */
export type PageTree = Node & { kind: "page" };

`, union(kindNames()), union(gapNames()), union(toneNames()), union(directionNames()),
		contrib.MaxDepth, contrib.MaxNodes, contrib.MaxTableRows, contrib.MaxPageBytes)

	fmt.Fprintf(&b, `// ─── the host a plugin reaches ─────────────────────────────────────────────
// A function below is there only when the manifest declared its capability; a
// call to one it did not declare throws ext.CapabilityError.

export interface Block {
  /** Absent in the view a derive hook is handed; the text is what it reads. */
  id?: string;
  text: string;
}

export interface CardType {
  id: string;
  fields: string[];
  version: number;
}

export interface DerivedCard {
  typeId: string;
  ordinal: number;
  fields: Record<string, string>;
  /** Field names the type does not carry; the host logs and drops them. */
  unknown?: string[];
}

export interface Note {
  id: string;
  title: string;
  blocks: Block[];
}

export interface Card {
  id: string;
  block: string;
  type: string;
  ordinal: number;
  /** The user's own edited fields; the rest are derived when the card renders. */
  fields?: Record<string, string>;
  edited?: boolean;
  status: CardStatus;
  due?: string;
  reviews: number;
}

/** One line of the review log, as a plugin reads it: no voided events. */
export interface ReviewEvent {
  seq: number;
  card: string;
  rating: Rating;
  at: string;
  scheduler?: string;
}

export type Rating = "again" | "hard" | "good" | "easy";

/**
 * A card's FSRS state. It is the host's shape and opaque to a plugin: carry it
 * back unchanged; the arithmetic stays the host's.
 */
export interface ScheduleState {
  stability: number;
  difficulty: number;
  due?: string;
  lastReview?: string;
  reviews: number;
  lastRating?: Rating;
}

export interface Policy {
  family: string;
  version: string;
  retention: number;
}

export interface SummaryInput {
  reviewed: number;
  dueTomorrow: number;
  accuracy: number;
}

export interface Summary {
  tone: "quiet" | "celebrated";
  /** Markdown the host draws under its own wording. */
  lines: string[];
}

/** A notification, not a veto: the host ignores the answer. */
export interface Event {
  /** note.saved, card.created or review.recorded. */
  kind: string;
  id: string;
}

/** What a contributed command and a page's data are asked with. */
export interface CommandInput {
  /** The name the contribution declared after command:. */
  name: string;
  context: Partial<Context> & { "card.id"?: string; "note.id"?: string };
}

/** What a command callback answers: the host applies the result. */
export interface CommandResult {
  result?: "navigate" | "refresh" | "toast" | "none";
  /** The page to open when result is "navigate". */
  page?: string;
  /** The message when result is "toast": a %%key%% or a literal. */
  message?: string;
}

export declare const remit: {
  /** remit.echo: answers the value back. For a plugin's own tests. */
  echo(value: unknown): unknown;
  /** remit.now: the time as RFC 3339. */
  now(): string;
  notes: {
    /** notes:read */
    list(): Note[];
    get(id: string): Note | null;
    search(text: string): Note[];
  };
  cards: {
    /** cards:write */
    create(block: string): Card;
    update(id: string, patch: { fields?: Record<string, string>; status?: CardStatus }): Card;
    delete(id: string): void;
  };
  review: {
    /** review:read */
    history(card: string): ReviewEvent[];
    dueCount(): number;
    /** review:write */
    record(card: string, rating: Rating, at?: string): Card;
  };
  fsrs: {
    /** schedule:fsrs: advances a state by one answer. */
    review(state: ScheduleState, rating: Rating, at?: string): ScheduleState;
  };
  store: {
    /** store:own: the plugin's own value, under its own id. */
    get(): string | null;
    set(value: string): void;
  };
};

// ─── the exports the host calls ────────────────────────────────────────────
// A plugin exports the hooks its manifest declares; the names are the host's.

export interface Hooks {
  describe(): { name: string; version: string };
  deriveBlock(block: Block, types: CardType[]): DerivedCard[];
  identity(): string;
  on_event(event: Event): void;
  policy(): Policy;
  summary(session: SummaryInput): Summary;
  /** What a contributed command and a page's data answer. */
  command(input: CommandInput): CommandResult | PageTree;
}
`)

	return []byte(b.String())
}

// hookNames is the hook vocabulary in a stable order.
func hookNames() []string {
	names := make([]string, 0, len(ext.Hooks))
	for name := range ext.Hooks {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// hookContracts is the implements body: one line per hook and its version.
func hookContracts() string {
	var b strings.Builder
	for _, name := range hookNames() {
		fmt.Fprintf(&b, "  %q: %d;\n", name, ext.Hooks[name])
	}
	return b.String()
}

// contextFields is the Context body: one line per key and the value it answers.
// contextTypes names the type of every key; a key without one reads as a union
// of the two kinds a context value is, and the drift test says which key.
func contextFields() string {
	var b strings.Builder
	for _, key := range contrib.ContextKeys {
		typ, ok := contextTypes[key]
		if !ok {
			typ = "string | boolean"
		}
		fmt.Fprintf(&b, "  %q: %s;\n", key, typ)
	}
	return b.String()
}

// contextTypes is what each when key answers, as the host's Context documents.
