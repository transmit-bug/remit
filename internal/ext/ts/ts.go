// union is a TypeScript union of quoted strings.
func union(values []string) string {
	literals := make([]string, 0, len(values))
	for _, value := range values {
		literals = append(literals, quoted(value))
	}
	return strings.Join(literals, " | ")
}

// quotedAll is a union of already-quoted strings.
func quotedAll(values []string) string { return strings.Join(values, " | ") }

// quoted is one string literal, with its quotes escaped.
func quoted(value string) string {
	return `"` + strings.ReplaceAll(value, `"`, `\"`) + `"`
}

// navNames, settingTypeNames, kindNames, gapNames, toneNames and directionNames
